// Package gencontract turns contract/registry.yaml into Go constants.
//
// The registry is the one place a name shared with the app is written down.
// Hand-copying those names is how this codebase ended up with three separate
// authorisation namespaces, so the box reads the file instead of retyping it.
//
// Run it with `go generate ./internal/...` from go/. It stays in the box but
// writes the wire constants and the push table into go/protocol, the module
// FTW Cloud imports.
package gencontract

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Registry is the subset of the YAML the box needs. Fields the app owns alone
// (carrier states) are deliberately absent: generating a constant the box
// never uses only invites someone to use it.
type Registry struct {
	Version      int           `yaml:"version"`
	FrozenFields map[int]field `yaml:"frozen_fields"`
	// ExtraFields share the frozen set's ids on the wire but are not part of
	// the core view: depth a node's own view draws when the box sends it.
	ExtraFields  map[int]field `yaml:"extra_fields"`
	Capabilities []string      `yaml:"capabilities"`
	Scopes       []struct {
		Name string `yaml:"name"`
		Desc string `yaml:"desc"`
	} `yaml:"scopes"`
	Roles map[string]struct {
		Label  string   `yaml:"label"`
		Scopes []string `yaml:"scopes"`
	} `yaml:"roles"`
	Ops []struct {
		Name  string `yaml:"name"`
		Scope string `yaml:"scope"`
		// Agent is the scope that opens the op to an agent, empty when
		// none does.
		Agent string `yaml:"agent"`
		Desc  string `yaml:"desc"`
	} `yaml:"ops"`
	Modes []struct {
		Key  string `yaml:"key"`
		Tier string `yaml:"tier"`
	} `yaml:"modes"`
	Errors []struct {
		Code      string `yaml:"code"`
		Retryable bool   `yaml:"retryable"`
		Desc      string `yaml:"desc"`
	} `yaml:"errors"`
	SourceStates []string `yaml:"source_states"`
	// CloudScopes and CloudPurposes bound what an owner can let the box share
	// with FTW Cloud, and what for.
	CloudScopes   []string `yaml:"cloud_scopes"`
	CloudPurposes []string `yaml:"cloud_purposes"`
	// AgentArgs is what an agent may put in each op it can name, and
	// Reads the reads it may send with the scope each needs.
	AgentArgs map[string][]struct {
		Name     string   `yaml:"name"`
		Kind     string   `yaml:"kind"`
		Unit     string   `yaml:"unit"`
		Min      *float64 `yaml:"min"`
		Max      *float64 `yaml:"max"`
		Values   []string `yaml:"values"`
		Required bool     `yaml:"required"`
		Cap      string   `yaml:"cap"`
		Label    string   `yaml:"label"`
	} `yaml:"agent_args"`
	Reads []struct {
		Msg   string `yaml:"msg"`
		Scope string `yaml:"scope"`
		Desc  string `yaml:"desc"`
	} `yaml:"reads"`
	Resolutions map[string]struct {
		TileSpanMs    int64  `yaml:"tile_span_ms"`
		RetentionDays int    `yaml:"retention_days"`
		Source        string `yaml:"source"`
	} `yaml:"resolutions"`
	// Cars: their field names, the two enums and what a charger carries
	// about its car (docs/cars.md).
	CarFields        []carField `yaml:"car_fields"`
	CarSoCSources    []string   `yaml:"car_soc_sources"`
	CarIdentifiedBy  []string   `yaml:"car_identified_by"`
	ChargerCarFields []carField `yaml:"charger_car_fields"`
}

// carField is one entry of car_fields or charger_car_fields.
type carField struct {
	Name string `yaml:"name"`
	Kind string `yaml:"kind"`
	Desc string `yaml:"desc"`
}

// field is one entry of frozen_fields or extra_fields.
type field struct {
	Name string `yaml:"name"`
	Kind string `yaml:"kind"`
	Unit string `yaml:"unit"`
}

// Generate renders the constant file for package protocol. Exported and byte-deterministic so the
// drift test can re-run it in memory and compare, rather than shelling out.
func Generate(raw []byte) ([]byte, error) {
	var reg Registry
	if err := yaml.Unmarshal(raw, &reg); err != nil {
		return nil, fmt.Errorf("parse registry: %w", err)
	}

	if err := checkFields(reg); err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gencontract from contract/registry.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package protocol\n\n")

	fmt.Fprintf(&b, "// ContractVersion is the registry revision these names came from.\n")
	fmt.Fprintf(&b, "const ContractVersion = %d\n\n", reg.Version)

	writeFields(&b, reg)
	writeCaps(&b, reg)
	writeScopes(&b, reg)
	writeRoleNames(&b, reg)
	writeCloud(&b, reg)
	writeOps(&b, reg)
	writeAgentArgs(&b, reg)
	writeReads(&b, reg)
	writeErrors(&b, reg)
	writeSourceStates(&b, reg)
	writeResolutions(&b, reg)
	writeRegistryModes(&b, reg)
	writeCars(&b, reg)

	return format.Source(b.Bytes())
}

// GenerateRoles renders the role table into package apiauth.
//
// Roles live there and not beside the other constants because three packages
// need the word "owner" — the enrolment record, the HTTP layer's local caller
// and the app protocol's gate — and apiauth is the only one all three can
// import without dragging the box in behind it.
func GenerateRoles(raw []byte) ([]byte, error) {
	var reg Registry
	if err := yaml.Unmarshal(raw, &reg); err != nil {
		return nil, fmt.Errorf("parse registry: %w", err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gencontract from contract/registry.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package apiauth\n\n")
	writeRoles(&b, reg)

	return format.Source(b.Bytes())
}

// checkFields refuses a registry where one id or one name means two things.
// A delta and FTW Cloud's live body key fields by id alone, so the frozen
// set and the extra fields are one space on the wire. Extra fields sit above
// the frozen set too: lane 0 drops the highest id first when a delta does not
// fit, and the core view must be the last thing to go.
func checkFields(reg Registry) error {
	highestFrozen := 0
	names := map[string]int{}
	for id, f := range reg.FrozenFields {
		highestFrozen = max(highestFrozen, id)
		names[f.Name] = id
	}
	for id, f := range reg.ExtraFields {
		if _, ok := reg.FrozenFields[id]; ok {
			return fmt.Errorf("field id %d is both frozen and extra", id)
		}
		if id <= highestFrozen {
			return fmt.Errorf("extra field %d (%s) sits among the frozen ids", id, f.Name)
		}
		if other, ok := names[f.Name]; ok {
			return fmt.Errorf("field name %s is both %d and %d", f.Name, other, id)
		}
		names[f.Name] = id
	}
	return nil
}

func sortedIDs(fields map[int]field) []int {
	ids := make([]int, 0, len(fields))
	for id := range fields {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	return ids
}

func writeFields(b *bytes.Buffer, reg Registry) {
	all := make(map[int]field, len(reg.FrozenFields)+len(reg.ExtraFields))
	for id, f := range reg.FrozenFields {
		all[id] = f
	}
	for id, f := range reg.ExtraFields {
		all[id] = f
	}

	b.WriteString("// Fid is a telemetry field id. 1-9 are frozen permanently as of v1, so an\n")
	b.WriteString("// app of any age can draw the core view from them alone. Ids after the\n")
	b.WriteString("// frozen set are depth for a node's own view.\n")
	b.WriteString("type Fid uint32\n\n")
	b.WriteString("const (\n")
	for _, id := range sortedIDs(all) {
		f := all[id]
		unit := f.Unit
		if unit == "" {
			unit = "none"
		}
		fmt.Fprintf(b, "\t// Fid%s — %s, unit %s.\n", goName(f.Name), f.Kind, unit)
		fmt.Fprintf(b, "\tFid%s Fid = %d\n", goName(f.Name), id)
	}
	b.WriteString(")\n\n")

	writeFieldMaps(b, "FrozenFieldNames", "FrozenFieldUnits", "a frozen field id", reg.FrozenFields)
	writeFieldMaps(b, "FieldNames", "FieldUnits", "every field id, frozen or extra,", all)
}

func writeFieldMaps(b *bytes.Buffer, names, units, what string, fields map[int]field) {
	ids := sortedIDs(fields)
	fmt.Fprintf(b, "// %s maps %s to its registry name.\n", names, what)
	fmt.Fprintf(b, "var %s = map[Fid]string{\n", names)
	for _, id := range ids {
		fmt.Fprintf(b, "\tFid%s: %q,\n", goName(fields[id].Name), fields[id].Name)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "// %s maps %s to its unit, empty when it has none.\n", units, what)
	fmt.Fprintf(b, "var %s = map[Fid]string{\n", units)
	for _, id := range ids {
		fmt.Fprintf(b, "\tFid%s: %q,\n", goName(fields[id].Name), fields[id].Unit)
	}
	b.WriteString("}\n\n")
}

func writeCaps(b *bytes.Buffer, reg Registry) {
	b.WriteString("// Capabilities are presence, not levels. An app hides what is absent and\n")
	b.WriteString("// never compares versions.\n")
	b.WriteString("const (\n")
	for _, c := range reg.Capabilities {
		fmt.Fprintf(b, "\tCap%s = %q\n", goName(c), c)
	}
	b.WriteString(")\n\n")

	b.WriteString("// AllCapabilities is every capability name the registry defines.\n")
	b.WriteString("var AllCapabilities = []string{\n")
	for _, c := range reg.Capabilities {
		fmt.Fprintf(b, "\tCap%s,\n", goName(c))
	}
	b.WriteString("}\n\n")
}

func writeScopes(b *bytes.Buffer, reg Registry) {
	b.WriteString("// Scopes are an object and a verb. Roles are a projection over these,\n")
	b.WriteString("// never a replacement for them.\n")
	b.WriteString("const (\n")
	for _, s := range reg.Scopes {
		fmt.Fprintf(b, "\t// Scope%s — %s.\n", goName(strings.TrimPrefix(s.Name, "ftw.")), s.Desc)
		fmt.Fprintf(b, "\tScope%s = %q\n", goName(strings.TrimPrefix(s.Name, "ftw.")), s.Name)
	}
	b.WriteString(")\n\n")

	// The registry's own shape: an object and a verb. The verb is the
	// contract, so the write set is derived rather than listed — a hand-kept
	// list is one a new scope gets left out of. A hold changes something
	// now and a request once an owner confirms it; read and run change
	// nothing.
	b.WriteString("// WriteScopes is every scope that changes something, now or once an\n")
	b.WriteString("// owner confirms it.\n")
	b.WriteString("var WriteScopes = []string{\n")
	for _, s := range reg.Scopes {
		if !changes(s.Name) {
			continue
		}
		fmt.Fprintf(b, "\tScope%s,\n", goName(strings.TrimPrefix(s.Name, "ftw.")))
	}
	b.WriteString("}\n\n")
}

// changes reports whether a scope's verb changes something.
func changes(scope string) bool {
	for _, verb := range []string{".write", ".hold", ".request"} {
		if strings.HasSuffix(scope, verb) {
			return true
		}
	}
	return false
}

// writeRoleNames emits the role names into package protocol as well, for FTW
// Cloud, which reads a roster's roles and cannot import apiauth. The role
// table itself stays in apiauth; this is only the words.
func writeRoleNames(b *bytes.Buffer, reg Registry) {
	names := make([]string, 0, len(reg.Roles))
	for name := range reg.Roles {
		names = append(names, name)
	}
	sort.Strings(names)
	b.WriteString("// Roles, as the registry names them. apiauth holds what each carries.\n")
	b.WriteString("const (\n")
	for _, name := range names {
		fmt.Fprintf(b, "\t// Role%s — %s.\n", goName(name), reg.Roles[name].Label)
		fmt.Fprintf(b, "\tRole%s = %q\n", goName(name), name)
	}
	b.WriteString(")\n\n")
}

// writeCloud emits what an FTW Cloud grant may name. The scopes are listed
