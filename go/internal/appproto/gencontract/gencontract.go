// writeCars emits the car's enums as constants and its field names as lists.
// The names are struct tags in go/protocol, read back against these lists by
// TestCarStructsAreTheRegistrys, as the ops are against the command table.
func writeCars(b *bytes.Buffer, reg Registry) {
	b.WriteString("\n// Where a car's level comes from: the registry's car_soc_sources.\n")
	b.WriteString("const (\n")
	for _, s := range reg.CarSoCSources {
		fmt.Fprintf(b, "\tCarSoC%s = %q\n", goName(s), s)
	}
	b.WriteString(")\n\n")

	b.WriteString("// How the box knows which car is on a charger: the registry's\n")
	b.WriteString("// car_identified_by.\n")
	b.WriteString("const (\n")
	for _, s := range reg.CarIdentifiedBy {
		fmt.Fprintf(b, "\tCarIdentifiedBy%s = %q\n", goName(s), s)
	}
	b.WriteString(")\n\n")

	writeNames := func(name, what string, fields []carField) {
		fmt.Fprintf(b, "// %s is every name in the registry's %s. A dotted name is a\n", name, what)
		b.WriteString("// field of the object before the dot.\n")
		fmt.Fprintf(b, "var %s = []string{\n", name)
		for _, f := range fields {
			fmt.Fprintf(b, "\t%q, // %s\n", f.Name, f.Desc)
		}
		b.WriteString("}\n")
	}
	writeNames("CarFields", "car_fields", reg.CarFields)
	b.WriteString("\n")
	writeNames("ChargerCarFields", "charger_car_fields", reg.ChargerCarFields)
}

// errName turns E_CMD_EXPIRED into ErrCmdExpired.
func errName(code string) string {
	return "Err" + goName(strings.ToLower(strings.TrimPrefix(code, "E_")))
}

// goName turns a registry name into an exported Go identifier: dots,
// underscores and hyphens are word breaks, and a leading digit gets a prefix
// because "5m" is not an identifier.
func goName(s string) string {
	var out strings.Builder
	upper := true
	for _, r := range s {
		switch r {
		case '.', '_', '-':
			upper = true
		default:
			if upper {
				out.WriteString(strings.ToUpper(string(r)))
				upper = false
			} else {
				out.WriteRune(r)
			}
		}
	}
	name := out.String()
	if name != "" && name[0] >= '0' && name[0] <= '9' {
		name = "N" + name
	}
	return name
}

// PushCatalogue is the subset of contract/push-catalogue.yaml the box needs.
// The catalogue is the app's file — the app owns all prose — and push is the
// stated exception where the box must render text, so the box reads the file
// rather than retyping a sentence of it.
type PushCatalogue struct {
	Version int `yaml:"version"`
	Events  []struct {
		Kind  string `yaml:"kind"`
		Title string `yaml:"title"`
		Body  string `yaml:"body"`
	} `yaml:"events"`
}

// GeneratePush renders the push sentence table into package protocol.
//
// It lives beside the registry generator because the two files share one
// pairing rule: byte-identical with the app's copy, compared by CI on both
// sides, changed only in a pair of pull requests.
func GeneratePush(raw []byte) ([]byte, error) {
	var cat PushCatalogue
	if err := yaml.Unmarshal(raw, &cat); err != nil {
		return nil, fmt.Errorf("parse push catalogue: %w", err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gencontract from contract/push-catalogue.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package protocol\n\n")

	fmt.Fprintf(&b, "// PushCatalogueVersion is the catalogue revision these sentences came from.\n")
	fmt.Fprintf(&b, "const PushCatalogueVersion = %d\n\n", cat.Version)

	b.WriteString("// Push event kinds. Hand-writing one of these strings is what the\n")
	b.WriteString("// catalogue exists to stop.\n")
	b.WriteString("const (\n")
	for _, e := range cat.Events {
		fmt.Fprintf(&b, "\tPush%s = %q\n", goName(e.Kind), e.Kind)
	}
	b.WriteString(")\n\n")

	b.WriteString("// PushSentence is one lock-screen sentence, exactly as the app wrote it.\n")
	b.WriteString("// {arg} placeholders are filled from the event's own facts and nothing else.\n")
	b.WriteString("type PushSentence struct {\n\tTitle string\n\tBody  string\n}\n\n")

	b.WriteString("// PushSentences is every sentence a push may carry, keyed by kind.\n")
	b.WriteString("var PushSentences = map[string]PushSentence{\n")
	for _, e := range cat.Events {
		fmt.Fprintf(&b, "\tPush%s: {Title: %q, Body: %q},\n", goName(e.Kind), e.Title, e.Body)
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}
